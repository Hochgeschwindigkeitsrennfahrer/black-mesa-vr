#!/usr/bin/env python3
"""Bake Black Mesa's own left-hand poses from viewmodel reload clips into
src/vr_clip_hand_poses.h.

Input: one or more bmvr_log.txt files with "Hand pose dump:" blocks, written
by the mod with bmvr_dump_hand_pose 1 while bmvr_debug_vm_seq/_cycle hold a
clip frame (each block = inv(L_Wrist) * bone, raw game bones, model units).

    python3 -I tools/bake_clip_hand_poses.py LOG [LOG ...] > src/vr_clip_hand_poses.h
"""
import re
import sys

# (enum name, label, clip, cycle, object bone). Order = ClipHandPose::Id.
PICKS = [
    ("kMp5Mag", "mp5 magazine", "reload", "0.400", "Clip_New"),
    ("kMp5Bolt", "mp5 bolt", "reload_long", "0.200", "Bolt_New"),
    ("kGlockMag", "glock magazine", "gun_reload", "0.450", "bone_clip"),
    ("kGlockSlide", "glock slide", "draw_admire", "0.550", "Bone01"),
    ("kXbowMag", "crossbow magazine", "reload", "0.500", "clip_export_bone"),
    ("k357Loader", "357 speed loader", "gun_reload1", "0.700", "speed_loader"),
    ("kShell", "shotgun shell", "shell_reload1", "0.300", "bone_shell"),
    ("kRpgRocket", "rpg rocket", "gun_reload1", "0.300", "RPG_Projectile"),
    ("kPinHold", "grenade pin held", "pinpullthrow", "0.450", "Grenad_Pin1"),
    ("kPinPulled", "grenade pin pulled", "pinpullthrow", "0.600", "Grenad_Pin1"),
]
FINGERS = [f"L_{f}{s}" for f in ("Thumb", "Index", "Middle", "Ring", "Pinky") for s in (1, 2, 3)]


def read(paths):
    blocks = {}
    cur = None
    for p in paths:
        for line in open(p, errors="replace"):
            m = re.search(r"Hand pose dump: seq \d+ \((\S+)\) cycle ([\d.]+)", line)
            if m:
                cur = blocks.setdefault((m[1], m[2], len(blocks)), {})
                continue
            m = re.search(r"Hand pose dump:\s+(\S+)\s+([-\d.| ]+)$", line)
            if m and cur is not None:
                v = [float(x) for x in m[2].replace("|", " ").split()]
                if len(v) == 12:
                    cur[m[1]] = v
    return blocks


def fmt(v):
    return "{ " + ", ".join(f"{x:.4f}f" for x in v) + " }"


def main():
    blocks = read(sys.argv[1:])
    out = []
    out.append("// Generated by tools/bake_clip_hand_poses.py from bmvr_dump_hand_pose logs. Do not edit.")
    out.append("// Black Mesa's own left hand at one frame of a viewmodel clip, relative to")
    out.append("// L_Wrist (3x4 rows, model units): the held object's bone and the 15 finger")
    out.append("// joints (thumb, index, middle, ring, pinky; 3 each).")
    out.append("#pragma once")
    out.append("")
    out.append("namespace ClipHandPose")
    out.append("{")
    out.append("    enum Id { kNone = -1, " + ", ".join(f"{p[0]} = {i}" for i, p in enumerate(PICKS)) + f", kCount = {len(PICKS)} }};")
    out.append("")
    out.append("    struct Pose")
    out.append("    {")
    out.append("        const char* name;")
    out.append("        const char* clip;")
    out.append("        float cycle;")
    out.append("        const char* objectBone;")
    out.append("        float object[12];")
    out.append("        float fingers[15][12];")
    out.append("    };")
    out.append("")
    out.append("    inline constexpr Pose kPoses[kCount] = {")
    for enum, label, clip, cycle, obj in PICKS:
        cands = [b for (c, cy, _), b in blocks.items() if c == clip and cy == cycle and obj in b]
        if not cands:
            sys.exit(f"no dump for {clip} @ {cycle} with {obj}")
        b = cands[-1]
        missing = [n for n in [obj] + FINGERS if n not in b]
        if missing:
            sys.exit(f"{clip} @ {cycle}: missing {missing}")
        out.append(f'        {{ "{label}", "{clip}", {float(cycle):.3f}f, "{obj}",')
        out.append(f"          {fmt(b[obj])},")
        out.append("          {")
        for n in FINGERS:
            out.append(f"            {fmt(b[n])}, // {n}")
        out.append("          } },")
    out.append("    };")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
